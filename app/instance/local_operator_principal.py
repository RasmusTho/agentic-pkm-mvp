"""The private delegated local-operator principal record (MVR-03).

`docs/MULTI_VAULT_RUNTIME/VERSION_ACTIVE_CONTEXT_SELECTION.md` requires MVR-03 to own the
*missing producer* for the principal the active-context seam resolves. Before this slice the
runtime had credentials (`app/auth.py`) but no principal: an API key is a credential, and
`appInstallId` is instance identity, and neither is a principal.

This module supplies exactly that missing producer and nothing more:

- one opaque, server-minted `local_operator_role_id` denoting an **instance-scoped delegated
  operator role**, not the human's global identity,
- a private, versioned, mode-`0600` record under the MVR-01 instance-state boundary, with its
  own schema, monotonic revision, migration provenance, and a lock / atomic-write / fsync
  path modelled on `VaultRegistryStore`,
- server-derived subject binding: `trusted_loopback`, `trusted_companion_proxy`, and
  `api_key_credential` (by non-reversible fingerprint -- never the raw key),
- fail-closed preflight for ambiguous, missing, partial, or unsafe state, each naming an
  explicit provisioning action.

The role id is generated by CSPRNG. It is never derived from `appInstallId`, from the
credential value, from a path, or from a correlation id -- `test_instance_identity_never_
substitutes_for_principal_context` pins that.

Ordering rule the contract makes non-negotiable: the `minimum_runtime_principal` floor is
recorded **before** the first durable role write. `bootstrap()` refuses to write without
proof the floor already landed, so a crash before the floor leaves old auth state
authoritative and this migration untouched.
"""

